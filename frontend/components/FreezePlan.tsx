"use client";

import { useState } from "react";
import { Area, AreaChart, CartesianGrid, Legend, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";

import { money, pct, time, type InterdictionPlan } from "@/lib/api";

import { Card, Stat } from "./ui";

/** Where the traced money is, the freeze set that recovers the most of it, and the race between alert and cash-out. */
export function FreezePlan({ plan, currency = "INR" }: { plan: InterdictionPlan; currency?: string }) {
  const [draft, setDraft] = useState<string | null>(null);
  const share = plan.stolen ? plan.recoverable_now / plan.stolen : 0;

  const request = (account: string, amount: number) =>
    [
      `To: Nodal Officer, bank holding account ${account}`,
      `Subject: Request to place a debit hold on ${account} (reference ${plan.case_id})`,
      "",
      `Funds traceable to reported fraud against ${plan.victims.join(", ")} are held in account ${account}.`,
      `Amount traced to the victims and still held: ${money(amount, currency)} as of ${time(plan.as_of)}.`,
      `Total traced from the victims: ${money(plan.stolen, currency)}; already moved to cash or crypto: ${money(plan.escaped, currency)}.`,
      "",
      "Please place a hold on the traced amount pending investigation and confirm the action taken.",
      "",
      "Draft generated by Ripple from the transaction trail. Review before sending; this is not a legal determination.",
    ].join("\n");

  return (
    <div className="space-y-4">
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Stat label="Traced from victims" value={money(plan.stolen, currency)} hint={`${plan.victims.length} source${plan.victims.length === 1 ? "" : "s"}`} />
        <Stat label="Recoverable now" value={money(plan.recoverable_now, currency)} hint={`${pct(share)} of traced money`} tone="good" />
        <Stat label="Already escaped" value={money(plan.escaped, currency)} hint="cash, crypto or out of view" tone={plan.escaped > 0 ? "bad" : "default"} />
        <Stat
          label="Recoverable at first alert"
          value={plan.recoverable_share_at_first_alert != null ? pct(plan.recoverable_share_at_first_alert) : "n/a"}
          hint={plan.first_alert_at ? `alert at ${time(plan.first_alert_at)}` : "no alert in this trail"}
        />
      </div>

      <Card title={`Freeze plan: ${plan.freeze.length} account${plan.freeze.length === 1 ? "" : "s"}`}>
        {plan.freeze.length === 0 ? (
          <p className="text-sm text-slate-400">Nothing left to freeze: the traced money has already left.</p>
        ) : (
          <ol className="space-y-2">
            {plan.freeze.map((f, i) => (
              <li key={f.account_id} className="flex flex-col gap-2 rounded-lg border border-slate-800 bg-slate-950/50 p-3 sm:flex-row sm:items-center">
                <span className="flex h-6 w-6 shrink-0 items-center justify-center rounded-full bg-emerald-500/20 text-xs font-bold text-emerald-300">{i + 1}</span>
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-baseline gap-x-3">
                    <span className="font-mono text-sm font-semibold">{f.account_id}</span>
                    <span className="text-sm tabular-nums text-emerald-300">{money(f.recoverable, currency)}</span>
                    <span className="text-xs text-slate-500">disruption {f.collateral_cost.toFixed(1)}</span>
                  </div>
                  <p className="mt-0.5 text-xs text-slate-400">{f.reason}</p>
                </div>
                <button
                  onClick={() => setDraft(request(f.account_id, f.recoverable))}
                  className="shrink-0 rounded-md border border-slate-700 px-3 py-1.5 text-xs font-medium hover:bg-slate-800 focus:outline-none focus-visible:ring-2 focus-visible:ring-sky-400"
                >
                  Draft hold request
                </button>
              </li>
            ))}
          </ol>
        )}
        <p className="mt-3 text-xs text-slate-500">{plan.method}.</p>
      </Card>

      {plan.timeline.length > 1 && (
        <Card title="The race: money still recoverable over time">
          <div className="h-56">
            <ResponsiveContainer width="100%" height="100%">
              <AreaChart data={plan.timeline.map((p) => ({ ...p, t: new Date(p.ts).getTime() }))}>
                <CartesianGrid stroke="#1e293b" />
                <XAxis dataKey="t" type="number" domain={["dataMin", "dataMax"]} scale="time"
                       tickFormatter={(t) => new Date(t).toLocaleString("en-IN", { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" })}
                       stroke="#64748b" fontSize={11} />
                <YAxis stroke="#64748b" fontSize={11} tickFormatter={(v) => money(v, currency).replace(/\.\d+$/, "")} width={90} />
                <Tooltip labelFormatter={(t) => time(new Date(Number(t)).toISOString())}
                         formatter={(v) => money(Number(v), currency)}
                         contentStyle={{ background: "#0f172a", border: "1px solid #334155" }} />
                <Legend />
                <Area type="stepAfter" dataKey="recoverable" name="Still in mule accounts" stroke="#34d399" fill="#34d39933" />
                <Area type="stepAfter" dataKey="escaped" name="Escaped to cash or crypto" stroke="#f87171" fill="#f8717133" />
                {plan.first_alert_at && (
                  <ReferenceLine x={new Date(plan.first_alert_at).getTime()} stroke="#fbbf24" strokeDasharray="4 4"
                                 label={{ value: "Ripple alert", fill: "#fbbf24", fontSize: 11, position: "top" }} />
                )}
              </AreaChart>
            </ResponsiveContainer>
          </div>
        </Card>
      )}

      {draft && (
        <div role="dialog" aria-modal="true" aria-label="Draft hold request" className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4">
          <div className="w-full max-w-xl rounded-xl border border-slate-700 bg-slate-900 p-4">
            <h3 className="mb-2 text-sm font-semibold">Draft hold request</h3>
            <pre className="max-h-80 overflow-auto whitespace-pre-wrap rounded-lg bg-slate-950 p-3 text-xs text-slate-300">{draft}</pre>
            <div className="mt-3 flex justify-end gap-2">
              <button onClick={() => navigator.clipboard?.writeText(draft)} className="rounded-md border border-slate-700 px-3 py-1.5 text-xs hover:bg-slate-800">Copy</button>
              <button onClick={() => setDraft(null)} className="rounded-md bg-sky-600 px-3 py-1.5 text-xs font-semibold hover:bg-sky-500">Close</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
